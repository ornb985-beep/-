"""知识库内核 —— 让知识可追溯、可叠加进化、可安全复用。

## 这一层为什么必须是代码，不能只是 markdown

一堆写得很好的 markdown，三个月后一定会变成这样：

    有人加了一条没写出处的结论
    有人把某条改了，引用它的三处 playbook 还指着旧说法
    有人把被推翻的旧结论删掉了 —— 于是「为什么错」永远查不到了

这三件事都不是态度问题，是**没有闸就一定会发生**。
所以本模块只做一件事：**给知识库装上和数据层同样严格的闸**。

    schema.py   三轴分类 + 字段契约 + 置信档位（不给数字）
    parse.py    front-matter 解析，纯标准库
    store.py    加载全库、id 唯一性、链接图
    check.py    七条校验，任一不过即 ERROR
    index.py    确定性索引生成（零时钟、零 set 迭代）
    evolve.py   supersede / falsify —— **只增不删**

## 七条校验

    ① 无出处的条目不许存在，且仓库内路径必须真实存在
    ② 置信度不可手填，由证据等级确定性推出
    ③ external 分区隔离，不得单独支撑已验证结论
    ④ 证伪不删除：falsified 必须留下推翻它的证据
    ⑤ supersede 链双向一致、不成环
    ⑥ playbook 引用必须解析得到
    ⑦ 正文里的代码位置引用必须真实存在（重命名后不许静默失效）
"""

