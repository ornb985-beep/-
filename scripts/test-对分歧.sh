#!/usr/bin/env bash
# 对分歧工具的自测。不花钱、不联网。
#
# 守三件事:漏判抓得到、判级差异数得对、标记数得对——
# 这工具要是自己坏了还绿着,分歧就又变回"手感"了。
#
# 想亲眼看它会红:BREAK=1 bash scripts/test-对分歧.sh
#   会把沙盒里【工具本体】的漏判门槛改成 9999(等于把守恒检查掐掉),
#   整句吞掉就抓不到了,下面的断言必须红。注入点在被测代码上,不在期望值上。

set -uo pipefail
REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

FAILED=0
pass() { printf '  [通过] %s\n' "$1"; }
fail() { printf '  [失败] %s\n' "$1"; FAILED=1; }

SB="$(mktemp -d)"; trap 'rm -rf "$SB"' EXIT
cp "$REPO/scripts/对分歧.py" "$SB/对分歧.py"

if [ -n "${BREAK:-}" ]; then
  sed -i 's/^门槛 = 6/门槛 = 9999/' "$SB/对分歧.py"
fi

# 假产出 A:三行全覆盖原话,标记 [推断]×1 [猜测]×1
cat > "$SB/A.log" <<'EOF'
# 00 · 我听到的

原话：「我想做个小程序管老客户，老是忘了谁该回访，最好像微信那样打开就能用。」

| # | 你原话里的哪句 | 这是什么 | 轻重 | 为什么这么判 |
|---|---|---|---|---|
| 1 | 「做个小程序管老客户」 | 方案 | ★ | 形态第8步定 |
| 2 | 「老是忘了谁该回访」 | 痛点 | ★★★ | 频次词 |
| 3 | 「像微信那样打开就能用」 | 参照物 | ★★★ | 参照物解决的问题才是重点 |

他怕新工具麻烦 `[推断]`,我猜他默认自己会天天用 `[猜测]`
EOF

# 假产出 B:整句吞掉「像微信那样打开就能用」+ 第1句判级不同 + 标记 [推断]×2
cat > "$SB/B.log" <<'EOF'
原话：「我想做个小程序管老客户，老是忘了谁该回访，最好像微信那样打开就能用。」

| # | 你原话里的哪句 | 这是什么 | 轻重 | 为什么这么判 |
|---|---|---|---|---|
| 1 | "做个小程序管老客户" | 方案 | ★★ | 说法不同 |
| 2 | "老是忘了谁该回访" | 痛点 | ★★★ | 频次词 |

推断甲 `[推断]`,推断乙 `[推断]`
EOF

echo
echo "=== 对分歧工具自测 ==="

# ---------- 一、单份跑:全覆盖的要干净,吞句的要报漏 ----------
python3 "$SB/对分歧.py" "$SB/A.log" >/dev/null 2>&1
[ "$?" = 0 ] && pass "全覆盖的产出:退出码 0" || fail "全覆盖的产出:退出码该是 0"

python3 "$SB/对分歧.py" "$SB/B.log" >/dev/null 2>&1
[ "$?" = 1 ] && pass "吞了一整句的产出:退出码 1" || fail "吞了一整句的产出:退出码该是 1"

# ---------- 二、双份对比:三个数一个都不许错 ----------
out="$(python3 "$SB/对分歧.py" "$SB/A.log" "$SB/B.log" 2>&1)"; rc=$?

[ "$rc" = 1 ] && pass "对比模式发现漏判:退出码 1" || fail "对比模式发现漏判:退出码该是 1(实际 $rc)"

echo "$out" | grep -q "B.log:漏判 1 处" \
  && pass "漏判数对:B 漏 1 处" || fail "漏判数错:该报 B.log:漏判 1 处"
echo "$out" | grep -q "像微信那样打开就能用" \
  && pass "漏的正是被吞的那句(像微信那样…)" || fail "漏判清单里没有被吞的那句"
echo "$out" | grep -q "A.log:漏判 0 处" \
  && pass "没漏的不冤枉:A 漏 0 处" || fail "该报 A.log:漏判 0 处"

echo "$out" | grep -q "相同 1 对,不同 1 对" \
  && pass "判级差异数对:相同 1 / 不同 1" || fail "判级差异数错:该是 相同 1 对,不同 1 对"
echo "$out" | grep -q "前一份独有 1 句" \
  && pass "缺失数对:前一份独有 1 句" || fail "缺失数错:该报 前一份独有 1 句"

echo "$out" | grep -q '差额:  \[事实\]×0  \[推断\]×1  \[猜测\]×1' \
  && pass "标记差额对:[推断]差1 [猜测]差1" || fail "标记差额错"

# ---------- 三、解析不了必须响,不许静默(跳过不等于通过) ----------
printf '原话：「随便一句」\n没有表格\n' > "$SB/C.log"
python3 "$SB/对分歧.py" "$SB/C.log" >/dev/null 2>&1
[ "$?" = 2 ] && pass "没有判级表:退出码 2,不静默" || fail "没有判级表:退出码该是 2"

echo
if [ "$FAILED" = 0 ]; then echo "对分歧自测:全部通过"; else echo "对分歧自测:有失败项"; fi
exit "$FAILED"
